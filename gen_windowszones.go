//go:build ignore

// This program writes windowszones_gen.go from CLDR's table of Windows time
// zone names. Run it with go generate.
package main

import (
	"encoding/xml"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"slices"
	"strings"
)

const source = "https://raw.githubusercontent.com/unicode-org/cldr/release-49/common/supplemental/windowsZones.xml"

func main() {
	resp, err := http.Get(source)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("fetch %s: %s", source, resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}

	var doc struct {
		Zones []struct {
			Windows   string `xml:"other,attr"`
			Territory string `xml:"territory,attr"`
			IANA      string `xml:"type,attr"`
		} `xml:"windowsZones>mapTimezones>mapZone"`
	}
	if err := xml.Unmarshal(data, &doc); err != nil {
		log.Fatal(err)
	}

	// Territory 001 is CLDR's default zone for each Windows name.
	lines := []string{}
	for _, zone := range doc.Zones {
		if zone.Territory == "001" {
			iana, _, _ := strings.Cut(zone.IANA, " ")
			lines = append(lines, fmt.Sprintf("\t%q: %q,\n", zone.Windows, iana))
		}
	}
	if len(lines) == 0 {
		log.Fatal("no zones found")
	}
	slices.Sort(lines)

	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by gen_windowszones.go from %s. DO NOT EDIT.\n\n", source)
	out.WriteString("package tzatziki\n\nvar windowsZones = map[string]string{\n")
	out.WriteString(strings.Join(lines, ""))
	out.WriteString("}\n")

	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("windowszones_gen.go", formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}
